// Generates the shared JS→Rust→Solidity calendar-status fixture. Campana is independently
// transcribed in Rust and Solidity, so the canonical input fixture alone is too sparse to guard
// its holiday, half-day, and session-boundary constants.
import { readFileSync, writeFileSync } from 'node:fs';
import { CALENDAR_2026, etOffsetHours, marketStatus, STATUS } from '../core/campana.mjs';

const outFile = new URL('../onchain/tests/calendar-vectors.txt', import.meta.url);
const DAY_MS = 24 * 60 * 60 * 1000;
const SESSION_BOUNDARIES = [
  [9, 29], [9, 30], [12, 59], [13, 0], [15, 59], [16, 0],
];

const etWallToUnix = (year, month, day, hour, minute) => {
  const guess = Date.UTC(year, month - 1, day, hour, minute) / 1000;
  return guess - etOffsetHours(guess) * 3600;
};
const dateParts = (date) => [date.getUTCFullYear(), date.getUTCMonth() + 1, date.getUTCDate()];
const isOpen = (timestamp) => {
  const status = marketStatus(timestamp).status;
  return status === STATUS.OPEN || status === STATUS.HALF_DAY ? 1 : 0;
};

// All normal/half-day session edges for every ET civil day, DST transition instants plus their
// one-hour and one-second neighbours, and a noon probe for every exceptional calendar day.
const timestamps = new Set();
for (let millis = Date.UTC(2026, 0, 1); millis < Date.UTC(2027, 0, 1); millis += DAY_MS) {
  const [year, month, day] = dateParts(new Date(millis));
  for (const [hour, minute] of SESSION_BOUNDARIES) timestamps.add(etWallToUnix(year, month, day, hour, minute));
}
for (const transition of [Date.UTC(2026, 2, 8, 7) / 1000, Date.UTC(2026, 10, 1, 6) / 1000]) {
  for (const delta of [-3600, -1, 0, 1, 3600]) timestamps.add(transition + delta);
}
for (const date of [...CALENDAR_2026.holidays, ...CALENDAR_2026.halfDays]) {
  const [year, month, day] = date.split('-').map(Number);
  timestamps.add(etWallToUnix(year, month, day, 12, 0));
}

const rows = [...timestamps].sort((a, b) => a - b);
const generated = [
  '# Generated by tests/generate-calendar-vectors.mjs; do not edit by hand.',
  '# unix_ts|expected_is_session_open',
  ...rows.map((timestamp) => `${timestamp}|${isOpen(timestamp)}`),
].join('\n') + '\n';

if (process.argv.includes('--write')) {
  writeFileSync(outFile, generated);
  console.log(`wrote ${rows.length} calendar vectors to ${outFile.pathname}`);
} else {
  const committed = readFileSync(outFile, 'utf8');
  if (committed !== generated) throw new Error('onchain/tests/calendar-vectors.txt is stale; run node tests/generate-calendar-vectors.mjs --write and commit the result');
  console.log(`verified ${rows.length} committed calendar vectors`);
}
