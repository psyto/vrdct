// Generates canonical JS input bytes and expected JS verdicts for the Rust parity test.
// Run `npm run generate:parity-vectors` after an intentional parser/encoding change; CI-style
// checks use `npm run test:canonical`, which fails if this committed file is stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { encodeRecords, inputsCommitment } from '../core/encode.mjs';
import { CALENDAR_2026 } from '../core/campana.mjs';
import { reexec as cmlsReexec } from '../claimtypes/closed-market-soundness.mjs';
import { reexec as solvencyReexec } from '../claimtypes/solvency.mjs';

const outFile = new URL('../onchain/tests/parity-vectors.txt', import.meta.url);
const unix = (y, m, d, hour, minute = 0, second = 0) => Math.floor(Date.UTC(y, m - 1, d, hour, minute, second) / 1000);
const cmlsClaim = (times) => ({
  claim_type: 'closed-market-liquidation-soundness',
  inputs: { observed: { observations: times.map((blockTime) => ({ blockTime })) } },
});
const solvencyClaim = (virtualValue, liability, inv2b_ok, staleRecords) => ({
  claim_type: 'reserve-solvency',
  inputs: { observed: { quantities: { virtualValue, liability, staleRecords, ...(inv2b_ok === undefined ? {} : { inv2b_ok }) } } },
});

const cmlsVectors = [
  ['calendar-first', [CALENDAR_2026.validFrom]],
  ['calendar-last', [CALENDAR_2026.validUntil - 1]],
  ['duplicate', [unix(2026, 8, 1, 16), unix(2026, 8, 1, 16)]],
  ['equal-adjacent', [unix(2026, 8, 1, 16), unix(2026, 8, 1, 16, 1), unix(2026, 8, 1, 16, 1)]],
  ['dst-start-before', [unix(2026, 3, 8, 6, 59, 59)]],
  ['dst-start-at', [unix(2026, 3, 8, 7)]],
  ['dst-end-before', [unix(2026, 11, 1, 5, 59, 59)]],
  ['dst-end-at', [unix(2026, 11, 1, 6)]],
  ['regular-open-before', [unix(2026, 8, 3, 13, 29, 59)]],
  ['regular-open-at', [unix(2026, 8, 3, 13, 30)]],
  ['regular-close-before', [unix(2026, 8, 3, 19, 59, 59)]],
  ['regular-close-at', [unix(2026, 8, 3, 20)]],
  ['weekend', [unix(2026, 8, 1, 16)]],
  ['holiday', [unix(2026, 7, 3, 16)]],
  ['half-day-open-at', [unix(2026, 11, 27, 14, 30)]],
  ['half-day-open-before-close', [unix(2026, 11, 27, 17, 59, 59)]],
  ['half-day-close-at', [unix(2026, 11, 27, 18)]],
  ['multi-chunk-201', Array.from({ length: 201 }, (_, i) => unix(2026, 8, 1, 16) + i * 60)],
];

const flags = { UNKNOWN: 0, GREEN: 1, YELLOW: 2, RED: 3, STALE: 4 };
const lines = [
  '# Generated by tests/generate-parity-vectors.mjs; do not edit by hand.',
  '# kind|label|expected_flag_id|canonical_record_bytes_hex|expected_inputs_hash_hex',
];
for (const [label, times] of cmlsVectors) {
  const claim = cmlsClaim(times);
  lines.push(`CMLS|${label}|${flags[cmlsReexec(claim.inputs).verdict.flag]}|${encodeRecords(claim).bytes.toString('hex')}|${inputsCommitment(claim).inputsHash.toString('hex')}`);
}

const u128s = [0n, 1n, (1n << 128n) - 2n, (1n << 128n) - 1n];
for (const virtualValue of u128s) {
  for (const liability of u128s) {
    for (const inv2b_ok of [false, true, undefined]) {
      for (const staleRecords of [0, 1, 0xffffffff]) {
        const claim = solvencyClaim(virtualValue.toString(), liability.toString(), inv2b_ok, staleRecords);
        const label = `backing=${virtualValue};liability=${liability};inv2b=${inv2b_ok ?? 'absent'};stale=${staleRecords}`;
        lines.push(`SOLVENCY|${label}|${flags[solvencyReexec(claim.inputs).verdict.flag]}|${encodeRecords(claim).bytes.toString('hex')}|${inputsCommitment(claim).inputsHash.toString('hex')}`);
      }
    }
  }
}

const generated = lines.join('\n') + '\n';
if (process.argv.includes('--write')) {
  mkdirSync(new URL('../onchain/tests/', import.meta.url), { recursive: true });
  writeFileSync(outFile, generated);
  console.log(`wrote ${lines.length - 2} parity vectors to ${outFile.pathname}`);
} else {
  const committed = readFileSync(outFile, 'utf8');
  if (committed !== generated) throw new Error('onchain/tests/parity-vectors.txt is stale; run npm run generate:parity-vectors and commit the result');
  console.log(`verified ${lines.length - 2} committed parity vectors`);
}
