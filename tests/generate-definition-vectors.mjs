// Generates the small cross-language fixture for the market PDA definition hash. The source
// descriptor is part of the seed: a JS/Rust disagreement here would make a visible market address
// bind different provenance than the resolver intended.
import { readFileSync, writeFileSync } from 'node:fs';
import { marketDefinitionHash, SOURCE_KIND } from '../core/encode.mjs';

const outFile = new URL('../onchain/tests/market-definition-vectors.txt', import.meta.url);
const hex = (n, byte) => Buffer.alloc(n, byte);
const rows = [
  {
    label: 'cmls-sourced', marketId: hex(32, 0x11), claimTypeId: 1, calendarVersion: 202601,
    nRecords: 3789, inputsHash: hex(32, 0x22),
    source: { kind: SOURCE_KIND.SOLANA_ACCOUNT_SIGNATURES, account: hex(32, 0x33), fromTs: 1785586259, toTs: 1785888421 },
    yesWhen: 2, bond: 2_000_000_000n, challengeWindowSecs: 3600,
  },
  {
    label: 'solvency-unsourced', marketId: hex(32, 0x44), claimTypeId: 2, calendarVersion: 202601,
    nRecords: 1, inputsHash: hex(32, 0x55),
    source: { kind: SOURCE_KIND.UNSOURCED, account: Buffer.alloc(32), fromTs: 0, toTs: 0 },
    yesWhen: 2, bond: 1_000_000_000n, challengeWindowSecs: 7200,
  },
];

const lines = [
  '# Generated by tests/generate-definition-vectors.mjs; do not edit by hand.',
  '# label|market_id_hex|claim_type|calendar_version|n_records|inputs_hash_hex|source_kind|source_account_hex|from_ts|to_ts|yes_when|bond|challenge_window_secs|definition_hash_hex',
  ...rows.map((r) => [
    r.label, r.marketId.toString('hex'), r.claimTypeId, r.calendarVersion, r.nRecords,
    r.inputsHash.toString('hex'), r.source.kind, r.source.account.toString('hex'), r.source.fromTs,
    r.source.toTs, r.yesWhen, r.bond, r.challengeWindowSecs,
    marketDefinitionHash(r).toString('hex'),
  ].join('|')),
];
const generated = lines.join('\n') + '\n';

if (process.argv.includes('--write')) {
  writeFileSync(outFile, generated);
  console.log(`wrote ${rows.length} definition-hash vectors to ${outFile.pathname}`);
} else if (process.argv.includes('--print')) {
  process.stdout.write(generated);
} else {
  const committed = readFileSync(outFile, 'utf8');
  if (committed !== generated) throw new Error('onchain/tests/market-definition-vectors.txt is stale; run node tests/generate-definition-vectors.mjs --write and commit the result');
  console.log(`verified ${rows.length} committed definition-hash vectors`);
}
